//! Client library for the [Mica](https://mica.io) network.
//!
//! Mica's API is gRPC over mutual TLS; the messages and clients here are generated from the
//! [public protos](https://github.com/1080network/proto) with prost and tonic.
//!
//! Enable the Cargo feature for each role you play:
//!
//! ```toml
//! mica-sdk = { version = "2.0.0-pre0", features = ["issuer"] }   # or "acceptor", or both
//! ```
//!
//! * [`mica::issuer`] (feature `issuer`) and [`mica::acceptor`] (feature `acceptor`): the services for each role
//! * [`mica::member`], [`mica::common`] and [`micashared`]: shared by every role, always available
//! * [`mtls`]: connects to Mica with mutual TLS
//!
//! ```no_run
//! use mica_sdk::mica::member::ping::v1::{ping_service_client::PingServiceClient, PingRequest};
//! use mica_sdk::mtls::{connect, MtlsCredentials};
//!
//! # async fn run() -> Result<(), Box<dyn std::error::Error>> {
//! let credentials = MtlsCredentials::from_files("rootca.crt", "client.crt", "client.key")?;
//! let channel = connect("https://api.example.mica.io:443", &credentials).await?;
//! let response = PingServiceClient::new(channel).ping(PingRequest {}).await?;
//! println!("{:?}", response.into_inner().status());
//! # Ok(())
//! # }
//! ```

pub mod mtls;

