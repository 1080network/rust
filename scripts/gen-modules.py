#!/usr/bin/env python3
"""Write src/generated/mod.rs: the module tree for the generated prost and tonic files.

prost writes one file per proto package (mica.issuer.service.v2.rs; for services it includes a .tonic.rs file) and
refers to other packages by relative `super::` paths, so the files must sit in modules that mirror the package hierarchy.
The issuer and acceptor trees are gated behind Cargo features of the same name.

Usage: gen-modules.py <directory containing the generated .rs files>
"""
import os
import sys

FEATURES = {"mica.issuer": "issuer", "mica.acceptor": "acceptor"}
KEYWORDS = {"type", "match", "mod", "use", "ref", "move", "async", "await", "dyn", "enum", "struct", "trait", "fn", "loop"}


def mod_name(part: str) -> str:
    return f"r#{part}" if part in KEYWORDS else part


def main(directory: str) -> None:
    packages: dict[str, list[str]] = {}
    for name in sorted(os.listdir(directory)):
        if not name.endswith(".rs") or name == "mod.rs":
            continue
        if name.endswith(".tonic.rs"):
            continue  # included by the prost file of the same package, which refers to it
        packages.setdefault(name[:-3], []).append(name)

    tree: dict = {}
    for package, files in packages.items():
        node = tree
        for part in package.split("."):
            node = node.setdefault(part, {})
        node["__files__"] = files

    lines = ["// @generated by scripts/gen-modules.py: do not edit.", ""]

    def emit(node: dict, path: str, depth: int) -> None:
        pad = "    " * depth
        for name in node.get("__files__", []):
            lines.append(f'{pad}include!("{name}");')
        for part in sorted(k for k in node if k != "__files__"):
            full = f"{path}.{part}" if path else part
            feature = FEATURES.get(full)
            if feature:
                lines.append(f'{pad}#[cfg(feature = "{feature}")]')
            lines.append(f"{pad}pub mod {mod_name(part)} {{")
            emit(node[part], full, depth + 1)
            lines.append(f"{pad}}}")

    emit(tree, "", 0)
    with open(os.path.join(directory, "mod.rs"), "w") as out:
        out.write("\n".join(lines) + "\n")
    print(f"wrote mod.rs for {len(packages)} packages")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
